## ============================================================
## Partition a known total prey biomass among prey species
## using a common Damuth allometric relationship
##
## D_si = a * M_si^b
##
## where:
##   D_si = density of instar i of species s (ind / km^2)
##   M_si = body mass of that instar (kg)
##   b    = Damuth exponent
##   a    = common normalization constant
##
## The value of 'a' is solved so that total prey biomass
## exactly equals the biomass imposed by Hatton.
##
## Species can have different numbers of instars.
## ============================================================

calculatePreyDensitiesFromBiomass <- function(
    massesBySpecies,
    totalPreyBiomassDensity,
    area,
    bDensity = -0.75
) {

    ## massesBySpecies must be a named list:
    ##
    ## list(
    ##     species1 = c(m1, m2, ...),
    ##     species2 = c(m1, m2, ...)
    ## )

    if (is.null(names(massesBySpecies))) {
        stop("massesBySpecies must be a named list.")
    }

    if (totalPreyBiomassDensity <= 0) {
        stop("totalPreyBiomassDensity must be > 0.")
    }

    if (area <= 0) {
        stop("area must be > 0.")
    }


    ## --------------------------------------------------------
    ## Biomass generated by each species if aDensity = 1
    ##
    ## density_i = M_i^b
    ##
    ## biomass_i = density_i * M_i
    ##            = M_i^(b + 1)
    ## --------------------------------------------------------

    biomassFactors <- sapply(
        massesBySpecies,
        function(M) {

            if (any(!is.finite(M)) || any(M <= 0)) {
                stop("All masses must be finite and > 0.")
            }

            sum(M^(bDensity + 1))
        }
    )


    ## --------------------------------------------------------
    ## Solve the common Damuth normalization constant.
    ##
    ## totalBiomass =
    ##
    ## a * SUM_s SUM_i M_si^(b + 1)
    ##
    ## therefore:
    ##
    ## a = totalBiomass /
    ##     SUM_s SUM_i M_si^(b + 1)
    ## --------------------------------------------------------

    aDensity <-
        totalPreyBiomassDensity /
        sum(biomassFactors)


    ## --------------------------------------------------------
    ## Calculate each species
    ## --------------------------------------------------------

    speciesResults <- lapply(
        names(massesBySpecies),
        function(sp) {

            M <- massesBySpecies[[sp]]

            ## Density per instar
            densitiesPerInstar <-
                aDensity * M^bDensity

            ## Biomass density per instar
            biomassPerInstar <-
                densitiesPerInstar * M

            ## Expected number in simulation area
            expectedIndividualsPerInstar <-
                densitiesPerInstar * area

            ## Integer numbers for simulation
            individualsPerInstar <-
                round(expectedIndividualsPerInstar)

            list(

                massesVector =
                    M,

                densitiesPerInstar =
                    densitiesPerInstar,

                biomassDensityPerInstar =
                    biomassPerInstar,

                totalDensity =
                    sum(densitiesPerInstar),

                totalBiomassDensity =
                    sum(biomassPerInstar),

                expectedIndividualsPerInstar =
                    expectedIndividualsPerInstar,

                individualsPerInstar =
                    individualsPerInstar
            )
        }
    )

    names(speciesResults) <-
        names(massesBySpecies)


    ## --------------------------------------------------------
    ## Diagnostics
    ## --------------------------------------------------------

    calculatedTotalBiomass <-
        sum(
            sapply(
                speciesResults,
                function(x)
                    x$totalBiomassDensity
            )
        )


    return(
        list(

            aDensity =
                aDensity,

            bDensity =
                bDensity,

            species =
                speciesResults,

            targetPreyBiomassDensity =
                totalPreyBiomassDensity,

            calculatedPreyBiomassDensity =
                calculatedTotalBiomass,

            biomassError =
                calculatedTotalBiomass -
                totalPreyBiomassDensity
        )
    )
}

massesVectorAlamosaurus<-as.vector(t(read.table(file.path(parametrisation_path, "animalia", "alamosaurus_sanjuanensis", "massesVectorAlamosaurus.txt"))))

massesVectorEdmontosaurus<-as.vector(t(read.table(file.path(parametrisation_path, "animalia", "edmontosaurus_anectens", "massesVectorEdmontosaurus.txt"))))

massesBySpecies = list(AlamosaurusMass = massesVectorAlamosaurus, 
EdmontosaurusMass = massesVectorEdmontosaurus)

